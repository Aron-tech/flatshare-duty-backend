<h2>10. Adatbiztonság</h2>
<p>Az alkalmazás és a szerver között minden adat titkosított (HTTPS/TLS) kapcsolaton utazik. A hozzáférési tokeneket a szerver csak lenyomatként tárolja, a háztartások adataihoz csak a tagjaik férnek hozzá, és a szerver kizárólag a hivatalos FlatShare alkalmazás kéréseit szolgálja ki.</p>

