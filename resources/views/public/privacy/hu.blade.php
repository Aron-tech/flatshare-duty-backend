<p>Regisztrációhoz nem kérünk jelszót: Google- vagy Apple-fiókkal jelentkezhetsz be, a hitelesítést a WorkOS szolgáltatás végzi. Bejelentkezéskor a következőket kapjuk meg és tároljuk:</p>
