    <li><strong>törlésre</strong> – lásd a 7. pontot;</li>
    <li><strong>az adatkezelés korlátozására</strong> és <strong>tiltakozásra</strong> a jogos érdeken alapuló adatkezelés ellen;</li>
    <li><strong>adathordozhatóságra</strong> – kérésre géppel olvasható formában átadjuk az általad megadott adatokat;</li>
    <li><strong>a hozzájárulás visszavonására</strong> – a push-értesítéseket a telefon beállításaiban bármikor kikapcsolhatod.</li>
