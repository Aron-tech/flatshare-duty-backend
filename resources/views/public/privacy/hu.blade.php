    <li>a nyelvi beállításod (magyar/angol).</li>
</ul>
<p>Ezen felül tároljuk az általad megadott becenevet.</p>

<h3>2.2. A háztartásokban keletkező adatok</h3>
<p>Az alkalmazás lényege a közös háztartás szervezése, ezért tároljuk:</p>
<ul>
    <li>a háztartásokat (név, csatlakozási kód, beállítások: pl. a heti vagy havi pontozási időszak), a tagságodat és a szerepköröd (admin, tag, gyerek);</li>
    <li>a feladatokat (név, kategória, nehézség, időtartam, ismétlődés, kiosztási mód) és azok előfordulásait: ki vállalta, ki és mikor teljesítette;</li>
    <li>a pontjaidat, pontmozgásaidat, heti/havi céljaidat és az esetleges büntetőpontokat;</li>
    <li>a feladatokhoz adott személyes súlyozásodat (mennyire szereted az adott feladatot) és a forgó beosztás sorrendjét;</li>
    <li>a feladatcseréket (felajánlás, elfogadás) és a kért türelmi napokat;</li>
    <li>a jutalmakat (név, leírás, pontérték) és beváltásaikat;</li>
    <li>a matricaalbumod matricáit;</li>
    <li>a tagok kilépésének nyilvántartását (hogy az adminok dönthessenek a kilépő tag feladatairól);</li>
    <li>a háztartás adatainak változásnaplóját (mi változott, mikor és ki módosította).</li>
</ul>

<h3>2.3. Értesítések és naptár</h3>
<ul>
    <li><strong>Push-értesítési token</strong> és az eszköz platformja (iOS/Android) – csak ha engedélyezed az értesítéseket. Kijelentkezéskor töröljük.</li>
    <li><strong>Naptár-előfizetés</strong>: ha bekapcsolod, egy titkos, véletlenszerű azonosítót tartalmazó linket hozunk létre, amellyel a naptáralkalmazásod lekérheti a háztartás feladatait (feladatnevek, határidők, felelősök neve). Aki ismeri a linket, látja ezeket az adatokat, ezért ne oszd meg; az alkalmazásban bármikor új linket kérhetsz, amivel a régi érvényét veszti.</li>
</ul>

<h3>2.4. Technikai adatok</h3>
<ul>
    <li>A bejelentkezett munkamenethez tartozó hozzáférési token (a szerveren csak titkosított lenyomatként) és az utolsó használat időpontja.</li>
    <li>A szerver naplói: IP-cím, a kérés időpontja és útvonala, hibaüzenetek – a szolgáltatás biztonsága és a hibák javítása érdekében.</li>
</ul>

<h3>2.5. A telefonodon tárolt adatok</h3>
<ul>
    <li>A bejelentkezési tokent a készülék biztonságos tárolójában (iOS Keychain / Android Keystore) tartjuk.</li>
    <li>A kiválasztott háztartást és a megjelenési beállításokat (téma, színpaletta, betűtípus, ikonkészlet) a készüléken tároljuk, ezek nem kerülnek a szerverre.</li>
    <li>A <strong>kamerát</strong> kizárólag a háztartás QR-kódjának beolvasására használjuk. A kép a készüléken kerül feldolgozásra, nem tároljuk és nem továbbítjuk.</li>
</ul>

<h3>2.6. Amit nem gyűjtünk</h3>
<p>Nem gyűjtünk helyadatot, névjegyeket, fényképeket, egészségügyi vagy pénzügyi adatot. Nem használunk hirdetést, hirdetési azonosítót, harmadik féltől származó analitikát vagy nyomkövetést (tracking), és az adataidat nem adjuk el senkinek.</p>

