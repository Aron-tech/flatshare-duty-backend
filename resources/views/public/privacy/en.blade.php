<h2>6. How long we keep data</h2>
<ul>
    <li>Account and household data: until you delete your account.</li>
    <li>Push token: until you sign out, or as long as the notification service reports it as valid.</li>
    <li>Change log: up to 365 days, then deleted automatically.</li>
    <li>Server logs: up to 14 days; backups: up to 30 days.</li>
    <li>If you leave a household, the history of your work there (completions, point transactions) is kept so the other members' scores stay accurate.</li>
</ul>

<h2>7. Deleting your account</h2>
<p>You can delete your account in the app at any time: <strong>Profile picture → Settings → Delete account</strong>. If you cannot access the app, you can request it by e-mail. On deletion:</p>
<ul>
    <li>your name, nickname, e-mail address and profile picture are irreversibly removed (the account is anonymized),</li>
    <li>your access and push tokens, personal settings and your WorkOS account are deleted, and your Sign in with Apple authorization is revoked at Apple,</li>
    <li>households you created are deleted for all their members,</li>
    <li>you leave households created by others; the shared history there is attributed to an anonymous "Deleted user" that cannot be linked to you.</li>
</ul>
<p>Details: <a href="{{ route('account-deletion', ['lang' => 'en']) }}">Delete your account and data</a>.</p>

<h2>8. Your rights</h2>
<p>Under the GDPR you have the right to:</p>
<ul>
    <li><strong>access</strong> – ask what data we hold about you and get a copy;</li>
    <li><strong>rectification</strong> – change your nickname and language in the app, your name and e-mail in your Google/Apple account;</li>
    <li><strong>erasure</strong> – see section 7;</li>
    <li><strong>restriction</strong> and to <strong>object</strong> to processing based on legitimate interest;</li>
    <li><strong>data portability</strong> – on request we provide the data you gave us in a machine-readable format;</li>
    <li><strong>withdraw consent</strong> – turn off push notifications in your phone's settings at any time.</li>
</ul>
<p>Send requests to the e-mail address above; we reply within one month. If you believe the processing infringes your rights, you can lodge a complaint with the Hungarian National Authority for Data Protection and Freedom of Information (NAIH, Falk Miksa utca 9–11, 1055 Budapest, <a href="https://naih.hu">naih.hu</a>), with the supervisory authority of your country of residence, or go to court.</p>

<h2>9. Children</h2>
<p>A "child" role exists within households, but creating an account requires an own Google or Apple account. Children under 16 may only use the app with the consent and supervision of a parent or legal guardian. A parent can request the deletion of a child's data at the e-mail address above.</p>

<h2>10. Security</h2>
<p>All data between the app and the server travels over an encrypted (HTTPS/TLS) connection. Access tokens are stored only as hashes, household data is accessible only to its members, and the server only serves requests from the official FlatShare app.</p>

