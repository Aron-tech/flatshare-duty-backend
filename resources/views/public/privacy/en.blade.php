<h2>2. What data we process</h2>

<h3>2.1. Account data</h3>
<p>We do not ask for a password: you sign in with your Google or Apple account. Authentication is handled by WorkOS, except Sign in with Apple on iPhone, which Apple handles directly with our server. On sign-in we receive and store:</p>
<ul>
    <li>first and last name,</li>
    <li>e-mail address (with Apple this may be a private relay address generated by Apple),</li>
    <li>the web address of your profile picture (we do not copy the image, it loads from Google's/Apple's servers),</li>
    <li>your internal WorkOS user ID, or with Sign in with Apple on iPhone your Apple user ID and an Apple sign-in token (stored encrypted, only so we can revoke your Apple sign-in when you delete the account),</li>
    <li>your language setting (Hungarian/English).</li>
</ul>
<p>We also store the nickname you set.</p>

<h3>2.2. Household data</h3>
<p>The app exists to organise a shared household, so we store:</p>
<ul>
    <li>households (name, join code, settings such as the weekly or monthly scoring period), your membership and role (admin, member, child);</li>
    <li>chores (name, category, difficulty, duration, recurrence, assignment mode) and their occurrences: who claimed them, who completed them and when;</li>
    <li>your points, point transactions, weekly/monthly goals and any penalty points;</li>
    <li>the personal weight you gave to chores (how much you like them) and the rotation order;</li>
    <li>chore swaps (offers, acceptances) and grace days you requested;</li>
    <li>rewards (name, description, point value) and their redemptions;</li>
    <li>the stickers in your sticker album;</li>
    <li>records of members leaving (so admins can decide about the chores of a former member);</li>
    <li>a change log of household data (what changed, when and by whom).</li>
</ul>

<h3>2.3. Notifications and calendar</h3>
<ul>
    <li><strong>Push notification token</strong> and device platform (iOS/Android) – only if you allow notifications. It is deleted when you sign out.</li>
    <li><strong>Calendar subscription</strong>: if you turn it on, we create a link containing a secret random identifier that lets your calendar app fetch the household's chores (chore names, due dates, assignees' names). Anyone with the link can see this data, so do not share it; you can request a new link in the app at any time, which invalidates the old one.</li>
</ul>

<h3>2.4. Technical data</h3>
<ul>
    <li>The access token of your signed-in session (stored on the server only as a hash) and its last use.</li>
    <li>Server logs: IP address, time and path of requests, error messages – for security and to fix bugs.</li>
</ul>

<h3>2.5. Data stored on your phone</h3>
<ul>
    <li>Your sign-in token is kept in the device's secure storage (iOS Keychain / Android Keystore).</li>
    <li>The selected household and your appearance settings (theme, palette, font, icon set) are stored on the device only.</li>
    <li>The <strong>camera</strong> is used only to scan a household's QR code. The image is processed on the device and is neither stored nor transmitted.</li>
</ul>

<h3>2.6. What we do not collect</h3>
<p>We do not collect location, contacts, photos, health or financial data. We use no advertising, advertising identifiers, third-party analytics or tracking, and we never sell your data.</p>

<h2>3. Who can see your data</h2>
<p>The other members of your household(s) can see your name (or nickname), profile picture, e-mail address, points, the chores you claimed and completed, your rewards and redemptions. Members of other households cannot see your data.</p>

